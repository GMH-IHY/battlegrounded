"""The first build's weapons: a one-handed sword and a hip dagger, low-poly parts only
(docs/art/ArtDirection.md: a weapon is at most 8 parts, flat colours, SmoothPlastic).

    python tools/models/weapons.py

Writes src/shared/Combat/WeaponModelsData.luau; the game builds the weapons from it
(WeaponModels.luau) and the animation tools draw them in previews.

Frames:
  SwordGrip  an animated bone (Motor6D) in the right hand, like a wrist. Its +Y is the blade.
             With no animation keying it, the blade points along the arm's forward (-Z): straight
             ahead when the arm hangs, straight up when the arm is raised forward (classic Roblox).
  Dagger     the dagger's own frame (+Y = blade, origin = middle of the grip). It's welded to one of
             two mounts: DaggerHip (sheathed, on the torso's left hip) or DaggerHand (drawn, left hand,
             same grip as the sword's).
  Sheath     the empty scabbard on the left hip (stays there when the dagger is drawn).
"""
import math
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_LUAU = os.path.join(ROOT, "src", "shared", "Combat", "WeaponModelsData.luau")

STEEL = (200, 204, 210)
STEEL_DARK = (140, 146, 156)
IRON = (70, 72, 80)
LEATHER = (92, 60, 40)
LEATHER_DARK = (58, 38, 28)


def rx(d):
    a = math.radians(d)
    return np.array([[1, 0, 0], [0, math.cos(a), -math.sin(a)], [0, math.sin(a), math.cos(a)]])


def rz(d):
    a = math.radians(d)
    return np.array([[math.cos(a), -math.sin(a), 0], [math.sin(a), math.cos(a), 0], [0, 0, 1]])


def cf(pos, rot=None):
    m = np.eye(4)
    m[:3, 3] = pos
    if rot is not None:
        m[:3, :3] = rot
    return m


# Hand grip: the fist is the bottom of the arm; the grip runs through it front to back.
HAND = cf((0, -0.8, 0), rx(-90) @ rx(-25))  # blade tipped 25 deg down from the arm's forward at rest

# name -> (Part0, C0). SwordGrip is an animated bone; the others are weld mounts.
JOINTS = {"SwordGrip": ("Right Arm", HAND)}
MOUNTS = {
    "DaggerHand": ("Left Arm", HAND),
    # On the left hip, blade down and tipped a little back (+Z is behind the character).
    "DaggerHip": ("Torso", cf((-1.12, -0.45, 0.1), rx(165))),
    "Sheath": ("Torso", cf((-1.12, -0.45, 0.1), rx(165))),
}

# (group, name, size, CFrame relative to the group's frame, colour)
PARTS = [
    ("SwordGrip", "Grip", (0.24, 0.8, 0.24), cf((0, 0.05, 0)), LEATHER),
    ("SwordGrip", "Pommel", (0.34, 0.3, 0.34), cf((0, -0.45, 0)), IRON),
    ("SwordGrip", "Guard", (1.1, 0.2, 0.3), cf((0, 0.55, 0)), IRON),
    ("SwordGrip", "Blade", (0.42, 3.0, 0.1), cf((0, 2.15, 0)), STEEL),
    ("SwordGrip", "Fuller", (0.14, 2.5, 0.12), cf((0, 2.0, 0)), STEEL_DARK),
    ("SwordGrip", "Tip", (0.3, 0.3, 0.1), cf((0, 3.65, 0), rz(45)), STEEL),
    ("Dagger", "Grip", (0.2, 0.55, 0.2), cf((0, 0, 0)), LEATHER_DARK),
    ("Dagger", "Pommel", (0.26, 0.2, 0.26), cf((0, -0.33, 0)), IRON),
    ("Dagger", "Guard", (0.5, 0.1, 0.2), cf((0, 0.32, 0)), IRON),
    ("Dagger", "Blade", (0.28, 1.0, 0.07), cf((0, 0.87, 0)), STEEL),
    ("Dagger", "Tip", (0.2, 0.2, 0.07), cf((0, 1.37, 0), rz(45)), STEEL),
    ("Sheath", "Scabbard", (0.36, 1.2, 0.16), cf((0, 0.85, 0)), LEATHER),
]


def fmt_cf(m):
    p = m[:3, 3]
    r = m[:3, :3]
    nums = [p[0], p[1], p[2]] + [r[i, j] for i in range(3) for j in range(3)]
    return "CFrame.new(" + ", ".join(f"{0.0 if abs(x) < 5e-6 else x:.5f}" for x in nums) + ")"


def write_luau():
    counts = {}
    for group, *_ in PARTS:
        counts[group] = counts.get(group, 0) + 1
    assert counts["SwordGrip"] <= 8 and counts["Dagger"] + counts["Sheath"] <= 8, "a weapon is at most 8 parts"
    lines = [
        "--!strict",
        "-- WeaponModelsData (ModuleScript, ReplicatedStorage > Combat > WeaponModelsData)",
        "-- GENERATED by tools/models/weapons.py. Don't edit by hand: change the script and rerun it.",
        "-- Joints: animated bone Motor6Ds (C0 relative to Part0). Mounts: weld frames the dagger and",
        "-- sheath are attached with. Parts: CFrame relative to their group's frame (Bone = the group).",
        "",
        "export type Joint = { Name: string, Part0: string, C0: CFrame }",
        "export type PartSpec = { Bone: string, Name: string, Class: string, Shape: string, Size: Vector3, "
        "CFrame: CFrame, Color: Color3, Material: Enum.Material, Texture: string }",
        "",
        "local Joints: { Joint } = {",
    ]
    for name, (part0, c0) in JOINTS.items():
        lines.append(f'\t{{ Name = "{name}", Part0 = "{part0}", C0 = {fmt_cf(c0)} }},')
    lines += ["}", "", "local Mounts: { [string]: Joint } = {"]
    for name, (part0, c0) in MOUNTS.items():
        lines.append(f'\t{name} = {{ Name = "{name}", Part0 = "{part0}", C0 = {fmt_cf(c0)} }},')
    lines += ["}", "", "local Parts: { PartSpec } = {"]
    for group, name, size, rel, color in PARTS:
        lines.append(
            f'\t{{ Bone = "{group}", Name = "{name}", Class = "Part", Shape = "Block", '
            f"Size = Vector3.new({size[0]:.4f}, {size[1]:.4f}, {size[2]:.4f}), CFrame = {fmt_cf(rel)}, "
            f"Color = Color3.fromRGB({color[0]}, {color[1]}, {color[2]}), Material = Enum.Material.SmoothPlastic, "
            f'Texture = "" }},')
    lines += ["}", "", "return { Joints = Joints, Mounts = Mounts, Parts = Parts }", ""]
    open(OUT_LUAU, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {OUT_LUAU} ({len(PARTS)} parts)")


if __name__ == "__main__":
    write_luau()
