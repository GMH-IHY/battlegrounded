"""Moth wings and antennae: thin paper plates and rods (docs/art/ArtDirection.md, Ko-guy style).

    python tools/models/moth_wings.py

Writes src/shared/Movement/MothPartsData.luau (the game builds the wings from it, MothParts.luau)
and assets/textures/moth_wing_paper.png (upload it to Roblox, then paste its id into WING_TEXTURE
below and rerun to put the paper texture on the wings).

Bones (unchanged, so every Moth animation keeps working):
  Torso > RightForewing / LeftForewing / RightHindwing / LeftHindwing
  Head  > RightAntenna / LeftAntenna
Wing bone frame: X out along the wing, Y up it, Z = the wing's backward normal. Rotating the bone
about Y swings the wing (+ forward, - folds it back), about Z raises / lowers the tip.
The left side is the mirror image of the right: rel_left = S @ rel_right @ S, S = diag(-1, 1, 1).
"""
import math
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_LUAU = os.path.join(ROOT, "src", "shared", "Movement", "MothPartsData.luau")
OUT_TEXTURE = os.path.join(ROOT, "assets", "textures", "moth_wing_paper.png")

# Paste the uploaded paper texture here ("rbxassetid://123"). Empty = flat colour only.
WING_TEXTURE = ""

FORE_COLOR = (214, 204, 178)   # pale paper
HIND_COLOR = (186, 174, 146)   # a shade darker so the two plates read apart
ANTENNA_COLOR = (58, 50, 44)


def rx(d):
    a = math.radians(d)
    return np.array([[1, 0, 0], [0, math.cos(a), -math.sin(a)], [0, math.sin(a), math.cos(a)]])


def rz(d):
    a = math.radians(d)
    return np.array([[math.cos(a), -math.sin(a), 0], [math.sin(a), math.cos(a), 0], [0, 0, 1]])


def cf(pos, rot=None):
    m = np.eye(4)
    m[:3, 3] = pos
    if rot is not None:
        m[:3, :3] = rot
    return m


S = np.diag([-1.0, 1.0, 1.0, 1.0])


def mirror(m):
    return S @ m @ S


# Bone joints (Motor6D C0 relative to Part0), right side. Same frames as the previous wings.
RIGHT_JOINTS = {
    "RightForewing": ("Torso", cf((0.25, 0.45, 0.62), np.array([
        [0.92493, -0.06468, -0.37461], [0.06976, 0.99756, 0.0], [0.37369, -0.02613, 0.92718]]))),
    "RightHindwing": ("Torso", cf((0.25, -0.20, 0.66), np.array([
        [0.86128, 0.09052, -0.50000], [-0.10453, 0.99452, 0.0], [0.49726, 0.05226, 0.86603]]))),
    "RightAntenna": ("Head", cf((0.30, 0.50, -0.20))),
}


def plate(length, width, along, up, tilt):
    """A thin wing plate in its bone frame: its inner end `along` studs out, raised `up`,
    tip tilted `tilt` degrees up (+) or down (-)."""
    rot = rz(tilt)
    centre = rot @ np.array([length / 2, 0, 0]) + np.array([along, up, 0])
    return cf(centre, rot), (length, width, 0.05)


def rod(base, direction_rot, length, thick):
    d = direction_rot @ np.array([0, 1, 0])
    centre = np.array(base) + d * length / 2
    return cf(centre, direction_rot), (thick, length, thick), np.array(base) + d * length


def right_parts():
    parts = []
    m, size = plate(3.1, 1.05, 0.05, 0.3, 20)
    parts.append(("RightForewing", "Wing", size, m, FORE_COLOR, True))
    m, size = plate(2.3, 0.8, 0.05, -0.1, -14)
    parts.append(("RightHindwing", "Wing", size, m, HIND_COLOR, True))
    base_rot = rz(-16)
    m, size, end = rod((0, 0, 0), base_rot, 0.8, 0.1)
    parts.append(("RightAntenna", "Rod", size, m, ANTENNA_COLOR, False))
    tip_rot = base_rot @ rx(-38)
    m, size, _ = rod(end, tip_rot, 0.6, 0.08)
    parts.append(("RightAntenna", "Tip", size, m, ANTENNA_COLOR, False))
    return parts


def fmt_cf(m):
    p = m[:3, 3]
    r = m[:3, :3]
    nums = [p[0], p[1], p[2]] + [r[i, j] for i in range(3) for j in range(3)]
    return "CFrame.new(" + ", ".join(f"{0.0 if abs(x) < 5e-6 else x:.5f}" for x in nums) + ")"


def write_luau():
    joints = []
    for name, (part0, c0) in RIGHT_JOINTS.items():
        joints.append((name, part0, c0))
        joints.append((name.replace("Right", "Left"), part0, mirror(c0)))
    parts = []
    for bone, pname, size, rel, color, textured in right_parts():
        parts.append((bone, pname, size, rel, color, textured))
        parts.append((bone.replace("Right", "Left"), pname, size, mirror(rel), color, textured))

    lines = [
        "--!strict",
        "-- MothPartsData (ModuleScript, ReplicatedStorage > Movement > MothPartsData)",
        "-- GENERATED by tools/models/moth_wings.py. Don't edit by hand: change the script and rerun it.",
        "-- Paper wings (thin plates) and rod antennae. Joints: bone Motor6Ds (C0 relative to Part0).",
        "-- Parts: visual pieces, CFrame relative to their bone. Texture: an uploaded image id, or \"\".",
        "",
        "export type Joint = { Name: string, Part0: string, C0: CFrame }",
        "export type PartSpec = { Bone: string, Name: string, Class: string, Shape: string, Size: Vector3, "
        "CFrame: CFrame, Color: Color3, Material: Enum.Material, Texture: string }",
        "",
        "local Joints: { Joint } = {",
    ]
    for name, part0, c0 in joints:
        lines.append(f'\t{{ Name = "{name}", Part0 = "{part0}", C0 = {fmt_cf(c0)} }},')
    lines += ["}", "", "local Parts: { PartSpec } = {"]
    for bone, pname, size, rel, color, textured in parts:
        tex = WING_TEXTURE if textured else ""
        lines.append(
            f'\t{{ Bone = "{bone}", Name = "{pname}", Class = "Part", Shape = "Block", '
            f"Size = Vector3.new({size[0]:.4f}, {size[1]:.4f}, {size[2]:.4f}), CFrame = {fmt_cf(rel)}, "
            f"Color = Color3.fromRGB({color[0]}, {color[1]}, {color[2]}), Material = Enum.Material.SmoothPlastic, "
            f'Texture = "{tex}" }},')
    lines += ["}", "", "return { Joints = Joints, Parts = Parts }", ""]
    open(OUT_LUAU, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {OUT_LUAU} ({len(joints)} bones, {len(parts)} parts)")


def write_texture(size=128, seed=7):
    """Cream paper: soft grain, a few long fibres, faint veins, a slightly darker rim."""
    rng = np.random.default_rng(seed)
    base = np.array(FORE_COLOR, float)
    grain = rng.normal(0, 7, (size, size, 1))
    img = np.clip(base + grain, 0, 255).astype(np.uint8)
    im = Image.fromarray(img).filter(ImageFilter.GaussianBlur(0.6))
    draw = ImageDraw.Draw(im)
    for _ in range(40):  # fibres
        x, y = rng.uniform(0, size, 2)
        a = rng.uniform(0, math.pi)
        length = rng.uniform(6, 18)
        tone = int(rng.uniform(-18, 12))
        c = tuple(int(np.clip(v + tone, 0, 255)) for v in FORE_COLOR)
        draw.line([(x, y), (x + math.cos(a) * length, y + math.sin(a) * length)], fill=c, width=1)
    vein = tuple(int(v * 0.82) for v in FORE_COLOR)
    for k in range(3):  # veins fanning from the root (left edge)
        y1 = size * (0.25 + 0.25 * k)
        draw.line([(0, size / 2), (size, y1)], fill=vein, width=1)
    rim = tuple(int(v * 0.75) for v in FORE_COLOR)
    draw.rectangle([0, 0, size - 1, size - 1], outline=rim, width=3)
    os.makedirs(os.path.dirname(OUT_TEXTURE), exist_ok=True)
    im.save(OUT_TEXTURE)
    print(f"wrote {OUT_TEXTURE}")


if __name__ == "__main__":
    write_luau()
    write_texture()
